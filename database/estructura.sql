CREATE TABLE membresia (

    membresia_id INTEGER GENERATED BY DEFAULT AS IDENTITY,

    socio_id INTEGER NOT NULL,
    plan_id INTEGER NOT NULL,

    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,

    precio_contratado NUMERIC(10,2) NOT NULL,

    estado VARCHAR(12) NOT NULL DEFAULT 'ACTIVA',

    CONSTRAINT membresia_pk
        PRIMARY KEY (membresia_id),

    CONSTRAINT membresia_socio_fk
        FOREIGN KEY (socio_id)
        REFERENCES socio (socio_id),

    CONSTRAINT membresia_plan_fk
        FOREIGN KEY (plan_id)
        REFERENCES plan_membresia (plan_id),

    CONSTRAINT membresia_precio_check
        CHECK (precio_contratado > 0),

    CONSTRAINT membresia_fechas_check
        CHECK (fecha_fin >= fecha_inicio),

    CONSTRAINT membresia_estado_check
        CHECK (UPPER (estado) IN ('ACTIVA', 'VENCIDA', 'CANCELADA'))

);

CREATE TABLE pago (
    pago_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    membresia_id INTEGER NOT NULL,
    fecha_pago TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    monto NUMERIC(10,2) NOT NULL,
    metodo_pago VARCHAR(20) NOT NULL,
    estado VARCHAR(12) NOT NULL DEFAULT 'PENDIENTE',

    CONSTRAINT pago_pk PRIMARY KEY (pago_id),

    CONSTRAINT pago_membresia_fk
        FOREIGN KEY (membresia_id)
        REFERENCES membresia (membresia_id),

    CONSTRAINT pago_monto_check
        CHECK (monto > 0),

    CONSTRAINT pago_metodo_check
        CHECK (metodo_pago IN (
            'EFECTIVO',
            'TARJETA',
            'TRANSFERENCIA'
        )),

    CONSTRAINT pago_estado_check
        CHECK (UPPER (estado) IN (
            'PENDIENTE',
            'APROBADO',
            'RECHAZADO',
            'ANULADO'
        ))
);

CREATE TABLE clase (
    clase_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre_clase VARCHAR(50) NOT NULL,
    descripcion VARCHAR(150),
    entrenador_id INTEGER NOT NULL,
    especialidad_id INTEGER NOT NULL,
    fecha_hora TIMESTAMP NOT NULL,
    duracion_minutos INTEGER NOT NULL,
    cupo_maximo INTEGER NOT NULL,
    estado VARCHAR(12) NOT NULL DEFAULT 'PROGRAMADA',

    CONSTRAINT clase_pk PRIMARY KEY (clase_id),

    CONSTRAINT clase_entrenador_especialidad_fk
        FOREIGN KEY (entrenador_id, especialidad_id)
        REFERENCES entrenador_especialidad (entrenador_id, especialidad_id),

    CONSTRAINT clase_duracion_check
        CHECK (duracion_minutos > 0),

    CONSTRAINT clase_cupo_check
        CHECK (cupo_maximo > 0),

    CONSTRAINT clase_estado_check
        CHECK (UPPER(estado) IN (
    	'PROGRAMADA',
    	'FINALIZADA',
    	'CANCELADA'
)));

CREATE TABLE inscripcion_clase (
    socio_id INTEGER NOT NULL,
    clase_id INTEGER NOT NULL,
    fecha_inscripcion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR(12) NOT NULL DEFAULT 'INSCRITO',

    CONSTRAINT inscripcion_clase_pk
        PRIMARY KEY (socio_id, clase_id),

    CONSTRAINT inscripcion_clase_socio_fk
        FOREIGN KEY (socio_id)
        REFERENCES socio (socio_id),

    CONSTRAINT inscripcion_clase_clase_fk
        FOREIGN KEY (clase_id)
        REFERENCES clase (clase_id),

    CONSTRAINT inscripcion_clase_estado_check
        CHECK (UPPER (estado) IN (
            'INSCRITO',
            'CANCELADO'
        ))
);


-- triggers

-- validar que la fecha insertada para programar una clase es futura al dia de hoy
CREATE OR REPLACE FUNCTION validar_fecha_clase()
RETURNS TRIGGER AS $$
BEGIN

    IF NEW.fecha_hora < CURRENT_TIMESTAMP THEN
        RAISE EXCEPTION
        'No se puede programar una clase en una fecha u hora pasada.';
    END IF;

    RETURN NEW;

END;
$$ LANGUAGE plpgsql;


--validamos 3 cosas al inscribir una clase:
--inscribirse en clase programada y no en una finalizada
--no se puede inscribir a una clase con los cupos llenos
--se comprueba si el socio tiene membresia activa
CREATE TRIGGER clase_fecha_trg
BEFORE INSERT OR UPDATE OF fecha_hora
ON clase
FOR EACH ROW
EXECUTE FUNCTION validar_fecha_clase();

CREATE OR REPLACE FUNCTION validar_inscripcion()
RETURNS TRIGGER AS $$
DECLARE
    v_estado_clase VARCHAR(12);
    v_cupo_maximo INTEGER;
    v_inscritos INTEGER;
BEGIN

    IF UPPER(NEW.estado) = 'INSCRITO' THEN

        SELECT estado, cupo_maximo
        INTO v_estado_clase, v_cupo_maximo
        FROM clase
        WHERE clase_id = NEW.clase_id
        FOR UPDATE;

        IF UPPER(v_estado_clase) <> 'PROGRAMADA' THEN
            RAISE EXCEPTION
            'No se puede inscribir en una clase que no está PROGRAMADA.';
        END IF;

        SELECT COUNT(*)
        INTO v_inscritos
        FROM inscripcion_clase
        WHERE clase_id = NEW.clase_id
          AND UPPER(estado) = 'INSCRITO'
          AND socio_id <> NEW.socio_id;

        IF v_inscritos >= v_cupo_maximo THEN
            RAISE EXCEPTION
            'La clase ya alcanzó su cupo máximo de % personas.',
            v_cupo_maximo;
        END IF;

        IF NOT EXISTS (
            SELECT 1
            FROM membresia
            WHERE socio_id = NEW.socio_id
              AND UPPER(estado) = 'ACTIVA'
              AND CURRENT_DATE BETWEEN fecha_inicio AND fecha_fin
        ) THEN
            RAISE EXCEPTION
            'El socio no tiene una membresía activa y vigente.';
        END IF;

    END IF;

    RETURN NEW;

END;
$$ LANGUAGE plpgsql;


CREATE TRIGGER validar_inscripcion_trg
BEFORE INSERT OR UPDATE OF estado, clase_id
ON inscripcion_clase
FOR EACH ROW
EXECUTE FUNCTION validar_inscripcion();